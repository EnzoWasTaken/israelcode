#!/usr/bin/env node
// Generates src/phosphor-icons/: the Phosphor icons gg-app uses, each carrying only
// the weights the app renders it with (the barrel ships all six per icon).
//
//   node scripts/gen-icons.mjs          write src/phosphor-icons/
//   node scripts/gen-icons.mjs --check  exit 1 if src/phosphor-icons/ is stale
//
// Icons and weights come from scanning src/: every `XxxIcon` imported from
// "./phosphor-icons" (or the phosphor barrel), plus `weight="..."` / `weight={...}` on
// JSX tags. Every icon gets "regular". A weight on a tag that isn't an icon
// name (e.g. `const TabIcon = tab.icon; <TabIcon weight={...}>`) applies to
// every icon passed around as a value, since the scan can't follow it.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
export const OUT = join(SRC, "phosphor-icons");
const WEIGHTS = ["thin", "light", "regular", "bold", "fill", "duotone"];
const require = createRequire(join(ROOT, "package.json"));
const PKG_DIR = dirname(require.resolve("@phosphor-icons/react/package.json"));

function sourceFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return p === OUT ? [] : sourceFiles(p);
    return /\.tsx?$/.test(e.name) && p !== OUT ? [p] : [];
  });
}

/** Scans src/ and returns Map<iconName, Set<weight>> (sorted by name). */
export function scanIconUsage() {
  const files = sourceFiles(SRC).map((p) => ({ p, text: readFileSync(p, "utf8") }));
  const icons = new Map();
  const importRe =
    /import\s*\{([^}]*)\}\s*from\s*"(@phosphor-icons\/react|(?:\.\.?\/)+phosphor-icons)"/g;
  for (const { text } of files) {
    for (const m of text.matchAll(importRe)) {
      for (const spec of m[1].split(",")) {
        const name = spec.trim();
        if (/^[A-Z]\w*Icon$/.test(name)) icons.set(name, new Set(["regular"]));
      }
    }
  }
  const dynamicWeights = new Set();
  const valueIcons = new Set();
  const tagRe = /<([A-Z]\w*)((?:[^<>"{}]|"[^"]*"|\{(?:[^{}]|\{[^{}]*\})*\})*)>/g;
  for (const { p, text } of files) {
    for (const m of text.matchAll(tagRe)) {
      const w = /\bweight=("[^"]*"|\{(?:[^{}]|\{[^{}]*\})*\})/.exec(m[2]);
      if (!w) continue;
      // Every weight-name literal in the expression (comparands like "passed" drop out).
      const found = [...w[1].matchAll(/"(\w+)"/g)]
        .map((x) => x[1])
        .filter((x) => WEIGHTS.includes(x));
      if (!found.length) {
        throw new Error(
          `${relative(ROOT, p)}: can't read icon weights from weight=${w[1]}; ` +
            `use string literals (e.g. {on ? "fill" : "regular"}).`,
        );
      }
      const target = icons.has(m[1]) ? icons.get(m[1]) : dynamicWeights;
      for (const x of found) target.add(x);
    }
    const body = text.replace(importRe, "");
    for (const name of icons.keys()) {
      if (new RegExp(`(?<!</?)\b${name}\b`).test(body)) valueIcons.add(name);
    }
  }
  for (const name of valueIcons) for (const x of dynamicWeights) icons.get(name).add(x);
  return new Map([...icons].sort(([a], [b]) => a.localeCompare(b)));
}

function serialize(node) {
  if (typeof node === "string") return JSON.stringify(node);
  const { children, ...props } = node.props;
  const type = typeof node.type === "string" ? JSON.stringify(node.type) : "Fragment";
  const kids =
    children === undefined ? [] : [children].flat().filter((c) => c != null && c !== false);
  const args = [
    type,
    Object.keys(props).length ? JSON.stringify(props) : "null",
    ...kids.map(serialize),
  ];
  return `h(${args.join(", ")})`;
}

const HEADER = `// GENERATED by scripts/gen-icons.mjs — do not edit. Regenerate after using a new
// icon or weight: node scripts/gen-icons.mjs
`;

/**
 * Renders src/phosphor-icons/ as Map<fileName, content>: one module per icon
 * (so an icon only used by a lazy chunk stays in that chunk), a shared
 * factory, and an index re-exporting them.
 */
export async function renderIconsModule() {
  const usage = scanIconUsage();
  const files = new Map();
  files.set(
    "icon.ts",
    `${HEADER}import { createElement as h, forwardRef, type ReactElement } from "react";
import IconBase from "@phosphor-icons/react/dist/lib/IconBase";
import type { Icon, IconWeight } from "@phosphor-icons/react";

/** A Phosphor icon component carrying only the given weights. */
export function icon(displayName: string, weights: [IconWeight, ReactElement][]): Icon {
  const map = new Map(weights);
  const component = forwardRef<SVGSVGElement>((props, ref) =>
    h(IconBase, { ref, ...props, weights: map }),
  ) as Icon;
  component.displayName = displayName;
  return component;
}
`,
  );
  let index = `${HEADER}//
// Phosphor icons with only the weights gg-app renders (the barrel ships all six).
export type { Icon, IconProps, IconWeight } from "@phosphor-icons/react";
`;
  for (const [name, weights] of usage) {
    const base = name.replace(/Icon$/, "");
    const defs = (await import(pathToFileURL(join(PKG_DIR, "dist/defs", `${base}.es.js`)).href))
      .default;
    const entries = WEIGHTS.filter((w) => weights.has(w)).map((w) => {
      const el = defs.get(w);
      if (!el) throw new Error(`${name} has no "${w}" weight`);
      return `[${JSON.stringify(w)}, ${serialize(el)}]`;
    });
    files.set(
      `${name}.ts`,
      `${HEADER}import { createElement as h, Fragment } from "react";
import { icon } from "./icon";

export const ${name} = /* @__PURE__ */ icon(${JSON.stringify(name)}, [${entries.join(", ")}]);
`,
    );
    index += `export { ${name} } from "./${name}";
`;
  }
  files.set("index.ts", index);
  const prettier = (await import(pathToFileURL(require.resolve("prettier")).href)).default;
  const options = (await prettier.resolveConfig(join(OUT, "index.ts"))) ?? {};
  for (const [file, text] of files) {
    files.set(file, await prettier.format(text, { ...options, filepath: join(OUT, file) }));
  }
  return files;
}

/** Map<fileName, content> of what's on disk now. */
export function readIconsModule() {
  if (!existsSync(OUT)) return new Map();
  return new Map(readdirSync(OUT).map((f) => [f, readFileSync(join(OUT, f), "utf8")]));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = await renderIconsModule();
  if (process.argv.includes("--check")) {
    const now = readIconsModule();
    if (now.size !== next.size || [...next].some(([f, t]) => now.get(f) !== t)) {
      console.error("src/phosphor-icons/ is stale; run: node scripts/gen-icons.mjs");
      process.exit(1);
    }
  } else {
    rmSync(OUT, { recursive: true, force: true });
    mkdirSync(OUT, { recursive: true });
    for (const [f, t] of next) writeFileSync(join(OUT, f), t);
    console.log(`wrote ${next.size} files to ${relative(ROOT, OUT)}`);
  }
}
